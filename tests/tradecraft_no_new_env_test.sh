PASS=0; FAIL=0
pass() { PASS=$((PASS+1)); printf '  \033[0;32mPASS\033[0m %s\n' "$1"; }
fail() { FAIL=$((FAIL+1)); printf '  \033[0;31mFAIL\033[0m %s\n' "$1"; }

# The keys of one service's `environment:` map (two-space services, six-space keys).
service_env_keys() {
    awk -v svc="  $1:" '
        $0 == svc { inside = 1; next }
        inside && /^  [a-z]/ { exit }
        inside && /^    environment:/ { env = 1; next }
        inside && env && /^    [a-z_]+:/ { env = 0 }
        inside && env && match($0, /^      [A-Z][A-Z0-9_]*:/) { k = substr($0, 7, RLENGTH - 7); print k }
    ' "$2" | sort -u
}

# The keys .env.example names, set or commented out.
env_example_keys() {
    grep -oE '^[[:space:]]*#?[[:space:]]*[A-Z][A-Z0-9_]+=' "$1" | sed -E 's/^[[:space:]]*#?[[:space:]]*//; s/=$//' | sort -u
}

