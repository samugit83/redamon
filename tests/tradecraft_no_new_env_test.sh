check() {  # <name> <base list> <current list>
    local added
    added="$(comm -13 <(tr ' ' '\n' <<<"$2" | sed '/^$/d' | sort -u) <(sed '/^$/d' <<<"$3"))"
    if [[ -z "$3" ]]; then
        fail "$1: no key found (the parser no longer reads the file)"
    elif [[ -z "$added" ]]; then
        pass "$1: no key beyond the base's"
    else
        fail "$1: keys added since the base: $(tr '\n' ' ' <<<"$added")"
    fi
}

printf '\n\033[1m== no new environment variable (R-001) ==\033[0m\n'
