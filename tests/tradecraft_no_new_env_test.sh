check "webapp service" "$WEBAPP_BASE" "$(service_env_keys webapp "$COMPOSE")"
check ".env.example" "$ENV_EXAMPLE_BASE" "$(env_example_keys "$ENV_EXAMPLE")"

# The parser itself: a key planted in a copy is found and refused.
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
sed 's/^\(      NEO4J_URI: bolt:\/\/neo4j:7687\)$/\1\n      TRADECRAFT_SOMETHING: "1"/' "$COMPOSE" > "$TMP/compose.yml"
planted="$(service_env_keys agent "$TMP/compose.yml")"
if [[ "$planted" == *TRADECRAFT_SOMETHING* ]]; then pass "a planted agent key is read"; else fail "a planted agent key is not read"; fi
printf 'TRADECRAFT_SOMETHING=1\n' >> "$TMP/env.example"
if [[ "$(env_example_keys "$TMP/env.example")" == "TRADECRAFT_SOMETHING" ]]; then pass "a planted .env.example key is read"; else fail "a planted .env.example key is not read"; fi

printf '\n%d passed, %d failed\n' "$PASS" "$FAIL"
[[ "$FAIL" -eq 0 ]]
