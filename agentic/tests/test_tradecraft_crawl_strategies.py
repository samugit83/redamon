TEXT = "Synthetic technique text for the crawl tests. " * 20  # over 500 characters


def s(**values):
    return EffectiveSettings(values)


def html(title, links=(), body=TEXT, chrome=()):
    """A page; ``chrome`` links sit in its header, the others in its article."""
    head = "".join(f'<a href="{h}">{t}</a>' for h, t in chrome)
    anchors = "".join(f'<a href="{h}">{t}</a>' for h, t in links)
    title_tag = f"<title>{title}</title>" if title else ""
    return (f"<html><head>{title_tag}</head><body><header>{head}</header>"
            f"<main><article><p>{body}</p>{anchors}</article></main></body></html>")


def write_site(root: Path, host: str, files: dict) -> None:
    """``files``: path -> text. A path ending in ``/`` is a page (``index.html``); ``_status``
    maps a path to the status it answers."""
    base = root / host
    base.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        if path == "_status":
            import json
            (base / "_status.json").write_text(json.dumps(text))
            continue
        target = base / path.lstrip("/")
        if path.endswith("/"):
            target = target / "index.html"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def urlset(urls):
    locs = "".join(f"<url><loc>{u}</loc></url>" for u in urls)
    return f'<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{locs}</urlset>'


def sitemap_index(urls):
    locs = "".join(f"<sitemap><loc>{u}</loc></sitemap>" for u in urls)
    return f'<?xml version="1.0" encoding="UTF-8"?><sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{locs}</sitemapindex>'


def go(url, settings=None, *, fetcher=None, fake_clock=None, **kw):
    with clock.use_clock(fake_clock or FakeClock()):
        if fetcher is None:
            return run(c.crawl(url, settings or s(), **kw))
        with net.use_fetcher(fetcher):
            return run(c.crawl(url, settings or s(), **kw))


class NoModel(ScriptedChatModel):
    """A model that must never be called: an empty queue raises."""


class AlwaysFollow(ScriptedChatModel):
    def _next(self, messages):
        self.queue('{"action": "follow", "indices": [' + ",".join(str(i) for i in range(1, 101)) + '], "reason": "x"}')
        return super()._next(messages)


class GeneratedSite:
    """Page /p<n> links to /p<n*k+1..>: an endless site, so only the limits stop a crawl.
    Each fetch moves the fake clock by ``advance`` seconds."""

    def __init__(self, fan_out=5, advance=0.0, fake_clock=None, extra=()):
        self.fan_out, self.advance, self.clock, self.extra = fan_out, advance, fake_clock, extra
        self.fetched: list[str] = []

    async def __call__(self, url):
        self.fetched.append(url)
        if self.clock is not None:
            self.clock.advance(self.advance)
        n = int(url.rsplit("/p", 1)[1].split("?")[0]) if "/p" in url else 0
        links = [(f"{SITE}/p{n * self.fan_out + i}", f"Page {n * self.fan_out + i}") for i in range(1, self.fan_out + 1)]
        return c.CrawlFetch(html(f"Page {n}", list(self.extra) + links), url, 1)


