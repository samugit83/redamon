def test_auto_uses_sitemap(tmp_path):
    """AC-05: the blog's sitemap (named by its robots.txt) maps all 60 posts, with no model call
    and no page visited; a bigger sitemap stops at the website map limit."""
    model = NoModel()
    result = go(BLOG, s(**{"crawl.strategy": "auto"}), fetcher=FixtureFetcher(), llm=model)
    urls = [e.url for e in result.entries]
    assert len(urls) == 60 and all("/posts/" in u for u in urls)
    assert model.calls == 0 and result.llm_calls == 0 and result.stats["pages_fetched"] == 0
    assert result.stop_reason == "sitemap" and result.stats["strategy"] == "auto"
    assert result.stopped_because.startswith("auto: robots")
    assert all(e.source == "sitemap" and e.title for e in result.entries)
    assert result.entries[0].title == "01 Xss Note 1"

    pages = [f"{SITE}/notes/n{i}/" for i in range(150)]
    write_site(tmp_path, HOST, {"/": html("Home"), "/sitemap.xml": urlset(pages)})
    big = go(SITE + "/", s(**{"crawl.strategy": "auto", "knownTypes.maxMapEntries.website": 100}),
             fetcher=FixtureFetcher(tmp_path), llm=NoModel())
    assert [e.url for e in big.entries] == pages[:100]
    assert big.stop_reason == "max_map_entries" and "map limit" in big.stopped_because
    # Above the default page budget of the model-guided crawl (200 pages) when the map allows it.
    pages = [f"{SITE}/notes/n{i}/" for i in range(450)]
    write_site(tmp_path, HOST, {"/sitemap.xml": urlset(pages)})
    assert len(go(SITE + "/", s(**{"crawl.strategy": "auto"}), fetcher=FixtureFetcher(tmp_path)).entries) == 450


def test_auto_falls_back_to_llm(tmp_path):
    """No sitemap at all, or one whose every page the rules refuse: the model-guided crawl."""
    write_site(tmp_path, HOST, {"/": html("Home", [(f"{SITE}/a/", "A")]), "/a/": html("A")})
    model = ScriptedChatModel('{"action": "follow", "indices": [1], "reason": "x"}')
    result = go(SITE + "/", s(**{"crawl.strategy": "auto"}), fetcher=FixtureFetcher(tmp_path), llm=model)
    assert model.calls == 1 and result.stats["strategy"] == "llm"
    assert [e.url for e in result.entries] == [SITE + "/", SITE + "/a/"]
    assert result.stop_reason == "frontier_empty"

    write_site(tmp_path, HOST, {"/sitemap.xml": urlset([f"{SITE}/login/", f"{SITE}/tag/x/"])})
    model = ScriptedChatModel('{"action": "stop", "reason": "enough"}')
    result = go(SITE + "/", s(**{"crawl.strategy": "auto"}), fetcher=FixtureFetcher(tmp_path), llm=model)
    assert model.calls == 1 and result.stop_reason == "llm_stop"
    assert result.skipped["excluded"] == 2  # the sitemap's refused pages are still counted


def test_rules_no_llm_calls():
    """Rule-based follows every link the rules allow and never asks the model."""
    site = GeneratedSite(fan_out=3)
    model = NoModel()
    result = go(SITE + "/p0", s(**{"crawl.strategy": "rules", "crawl.maxDepth": 3}), fetch_page=site, llm=model)
    # Depth 3 with three links a page: 1 + 3 + 9 + 27 pages, all of them followed.
    assert model.calls == 0 and result.llm_calls == 0
    assert len(site.fetched) == 40 and result.stop_reason == "frontier_empty"
    assert result.stats["strategy"] == "rules" and len(result.entries) == 40
    # No model is needed at all, and links are not capped at the links-per-page setting.
    wide = GeneratedSite(fan_out=30)
    result = go(SITE + "/p0", s(**{"crawl.strategy": "rules", "crawl.maxDepth": 1, "crawl.linksPerPage": 5}),
                fetch_page=wide, llm=None)
    assert len(wide.fetched) == 31


