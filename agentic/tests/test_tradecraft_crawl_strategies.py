def test_keep_rules(tmp_path):
    write_site(tmp_path, HOST, {
        "/": html("Home", [(f"{SITE}/short/", "s"), (f"{SITE}/untitled/", "u"), (f"{SITE}/long/", "l")]),
        "/short/": html("Short", body="tiny"),
        "/untitled/": html("", body=TEXT),
        "/long/": html("Long"),
    })
    rules = {"crawl.strategy": "rules"}
    result = go(SITE + "/", s(**rules), fetcher=FixtureFetcher(tmp_path))
    assert {e.url for e in result.entries} == {SITE + "/", SITE + "/long/"}
    assert result.skipped["tooLittleText"] == 2

    no_title_needed = go(SITE + "/", s(**rules, **{"crawl.requireTitle": False}), fetcher=FixtureFetcher(tmp_path))
    assert SITE + "/untitled/" in {e.url for e in no_title_needed.entries}
    any_text = go(SITE + "/", s(**rules, **{"crawl.minTextChars": 0}), fetcher=FixtureFetcher(tmp_path))
    assert SITE + "/short/" in {e.url for e in any_text.entries}
    # A page that was not kept still has its links followed (keep and follow are separate).
    write_site(tmp_path, HOST, {"/": html("Home", [(f"{SITE}/long/", "l")], body="tiny")})
    assert [e.url for e in go(SITE + "/", s(**rules), fetcher=FixtureFetcher(tmp_path)).entries] == [SITE + "/long/"]


