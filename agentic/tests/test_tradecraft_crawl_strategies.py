def _breaks_a_rule(url: str) -> bool:
    """An oracle written apart from ``FollowRules``: host exact, under /docs/, matching the
    include list, outside the exclude list."""
    parts = urllib.parse.urlsplit(url)
    path = parts.path
    return (parts.hostname != HOST or not path.startswith("/docs/") or "/guide" not in path
            or any(seg in ("tag", "private") for seg in path.split("/")) or path.endswith(".png"))


def test_no_rule_breaking_entry(tmp_path):
    bad = [f"{SITE}/docs/tag/x/", f"{SITE}/docs/private/guide-9/", f"{SITE}/other/guide-1/",
           f"https://www.{HOST}/docs/guide-1/", "https://other.tc-fixture.test/docs/guide-1/",
           f"{SITE}/docs/guide-img.png", f"{SITE}/docs/notes/"]
    good = [f"{SITE}/docs/guide-{i}/" for i in range(1, 6)]
    every = bad + good
    pages = {"/docs/": html("Docs", [(u, u) for u in every]), "/sitemap.xml": urlset(every + [f"{SITE}/docs/"])}
    for u in every:
        p = urllib.parse.urlsplit(u)
        if p.hostname == HOST and p.path.endswith("/"):
            pages[p.path] = html(p.path, [(v, v) for v in every])
    write_site(tmp_path, HOST, pages)
    for host in (f"www.{HOST}", "other.tc-fixture.test"):
        write_site(tmp_path, host, {"/docs/guide-1/": html("Elsewhere")})
    rules = {"crawl.stayInFolder": True, "crawl.includePaths": ["guide*"],
             "crawl.excludePaths": ["tag/", "private", "*.png"], "crawl.maxDepth": 3}
    for strategy, model in (("llm", AlwaysFollow()), ("rules", None), ("auto", NoModel())):
        result = go(SITE + "/docs/", s(**{"crawl.strategy": strategy, **rules}), fetcher=FixtureFetcher(tmp_path), llm=model)
        urls = {e.url for e in result.entries}
        assert urls == set(good), strategy
        assert not [u for u in urls if _breaks_a_rule(u)], strategy


