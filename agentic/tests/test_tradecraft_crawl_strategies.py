@pytest.mark.parametrize("parallel", [1, 3, 8])
def test_follow_rules_parallel_requests(parallel):
    in_flight, peak, order = [0], [0], []

    async def fetch_page(url):
        in_flight[0] += 1
        peak[0] = max(peak[0], in_flight[0])
        await asyncio.sleep(0)
        await asyncio.sleep(0)
        in_flight[0] -= 1
        order.append(url)
        n = int(url.rsplit("/p", 1)[1])
        return c.CrawlFetch(html(f"Page {n}", [(f"{SITE}/p{n * 10 + i}", "x") for i in range(1, 11)]), url, 1)

    result = go(SITE + "/p0", s(**{"crawl.strategy": "rules", "crawl.parallel": parallel, "crawl.maxPages": 30}),
                fetch_page=fetch_page)
    assert peak[0] == parallel and result.stats["pages_fetched"] == 30
    # Pages are kept in the order they were queued, whatever order the downloads end in.
    assert [e.url for e in result.entries][:3] == [SITE + "/p0", SITE + "/p1", SITE + "/p2"]


