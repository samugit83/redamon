"""The website crawl's strategies and follow rules (T3.1, §4.4): Auto takes the sitemap as the
map (AC-05) and falls back to the model when there is none, Rule-based follows every allowed
link with no model, every limit stops the crawl and the first one reached wins (R-076), the
keep rules, each follow rule (R-078), no saved entry breaks a rule (AC-06), robots.txt read as
RFC 9309 says (R-094, R-230), the sitemap's limits (R-112) and the skip counts of the report.

Sites are written into a temporary folder and served by ``FixtureFetcher`` (no network), or
generated by an injected ``fetch_page``; the clock is ``FakeClock``; the model is scripted and
raises when a test did not expect a call.
"""

