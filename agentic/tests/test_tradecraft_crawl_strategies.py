def _offered(model):
    """The link paths of the first prompt, in the order offered."""
    lines = [ln for ln in model.prompts[0].splitlines() if "-> " in ln and ln.strip()[:1].isdigit()]
    return [ln.rsplit("-> ", 1)[1] for ln in lines]


def _rules_crawl(tmp_path, start, links, **settings):
    write_site(tmp_path, HOST, {urllib.parse.urlsplit(start).path or "/": html("Start", links)})
    for href, _t in links:
        parts = urllib.parse.urlsplit(href)
        if parts.hostname == HOST and parts.path.endswith("/"):
            write_site(tmp_path, HOST, {parts.path: html(parts.path)})
    return go(start, s(**{"crawl.strategy": "rules", "crawl.maxDepth": 1, **settings}), fetcher=FixtureFetcher(tmp_path))


