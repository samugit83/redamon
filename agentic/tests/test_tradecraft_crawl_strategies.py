def test_limits():
    rules = {"crawl.strategy": "rules", "crawl.maxDepth": 10}
    pages = go(SITE + "/p0", s(**rules), fetch_page=GeneratedSite())
    assert pages.stop_reason == "max_pages" and pages.stats["pages_fetched"] == 200 and len(pages.entries) == 200

    few = go(SITE + "/p0", s(**rules, **{"crawl.maxPages": 7}), fetch_page=GeneratedSite())
    assert few.stop_reason == "max_pages" and few.stats["pages_fetched"] == 7

    deep = go(SITE + "/p0", s(**{"crawl.strategy": "rules", "crawl.maxDepth": 2}), fetch_page=GeneratedSite(fan_out=2))
    assert deep.stop_reason == "frontier_empty" and deep.stats["pages_fetched"] == 7

    fake = FakeClock()
    timed = go(SITE + "/p0", s(**rules, **{"crawl.timeBudgetSec": 30}),
               fetch_page=GeneratedSite(advance=4, fake_clock=fake), fake_clock=fake)
    assert timed.stop_reason == "time_budget" and timed.stats["pages_fetched"] == 8

    capped = go(SITE + "/p0", s(**rules, **{"crawl.maxPages": 300, "knownTypes.maxMapEntries.website": 100}),
                fetch_page=GeneratedSite())
    assert capped.stop_reason == "max_map_entries" and len(capped.entries) == 100

    calls = go(SITE + "/p0", s(**{"crawl.maxLlmCalls": 3, "crawl.maxDepth": 10}),
               fetch_page=GeneratedSite(fan_out=1), llm=AlwaysFollow())
    assert calls.stop_reason == "max_llm_calls" and calls.llm_calls == 3


def test_first_limit_stops():
    """R-076: pages, model calls and time all bound; the crawl ends at the first one reached."""

    def crawl_with(**limits):
        fake = FakeClock()
        settings = s(**{"crawl.maxDepth": 10, **limits})
        return go(SITE + "/p0", settings, fetch_page=GeneratedSite(advance=1, fake_clock=fake), fake_clock=fake,
                  llm=AlwaysFollow())

    calls_first = crawl_with()  # 200 pages, 20 calls, 180 s: the calls run out after 20 pages
    assert calls_first.stop_reason == "max_llm_calls" and calls_first.stats["pages_fetched"] == 20
    time_first = crawl_with(**{"crawl.maxLlmCalls": 200})  # 180 s at a second a page
    assert time_first.stop_reason == "time_budget" and time_first.stats["pages_fetched"] == 180
    pages_first = crawl_with(**{"crawl.maxLlmCalls": 200, "crawl.timeBudgetSec": 1800})
    assert pages_first.stop_reason == "max_pages" and pages_first.stats["pages_fetched"] == 200


