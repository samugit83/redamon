def test_robots_rfc9309(tmp_path):
    ua = s().str("fetching.userAgent")
    parsed = robots.parse(SITE, 200, "User-agent: *\nDisallow: /private/\n\nUser-agent: RedAmon-Tradecraft\n"
                                     "Disallow: /no-bots/\n\nSitemap: https://cdn.tc-fixture.test/s.xml\n")
    assert parsed.allows(SITE + "/open/", ua) and not parsed.allows(SITE + "/no-bots/a", ua)
    assert parsed.allows(SITE + "/private/x", ua)  # a group for our agent replaces the * group
    assert parsed.sitemaps == ["https://cdn.tc-fixture.test/s.xml"]
    # A 4xx means "no rules": everything is allowed. A 5xx, or no answer, disallows everything.
    for status, allowed in ((404, True), (401, True), (403, True), (500, False), (503, False), (0, False)):
        verdict = robots.parse(SITE, status, "User-agent: *\nDisallow: /\n")
        assert verdict.allows(SITE + "/a", ua) is allowed, status
        assert verdict.sitemaps == []

    write_site(tmp_path, HOST, {"/": html("Home"), "/robots.txt": "User-agent: *\nDisallow: /x/\nSitemap: /s.xml\n"})
    write_site(tmp_path, "err.tc-fixture.test", {"/": html("Home"), "_status": {"/robots.txt": 503}})
    write_site(tmp_path, "none.tc-fixture.test", {"/": html("Home")})
    write_site(tmp_path, "gone.tc-fixture.test", {"_unreachable": ""})
    fetcher = FixtureFetcher(tmp_path)
    with net.use_fetcher(fetcher):
        read = run(robots.read(SITE + "/deep/page?q=1", s()))
        assert read.mode == robots.PARSED and not read.allows(SITE + "/x/y", ua) and read.allows(SITE + "/y", ua)
