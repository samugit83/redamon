def test_follow_rules_host_scope(tmp_path):
    links = [(f"https://www.{HOST}/w/", "www"), (f"https://docs.{HOST}/d/", "sub"),
             ("https://other.tc-fixture.test/o/", "other"), (f"{SITE}/same/", "same")]
    for host in (f"www.{HOST}", f"docs.{HOST}", "other.tc-fixture.test"):
        write_site(tmp_path, host, {"/w/": html("W"), "/d/": html("D"), "/o/": html("O")})

    def kept(scope):
        result = _rules_crawl(tmp_path, SITE + "/", links, **{"crawl.hostScope": scope})
        return {urllib.parse.urlsplit(e.url).hostname for e in result.entries}, result.skipped["outOfScope"]

    assert kept("exact") == ({HOST}, 3)
    assert kept("www") == ({HOST, f"www.{HOST}"}, 2)
    assert kept("subdomains") == ({HOST, f"www.{HOST}", f"docs.{HOST}"}, 1)


def test_follow_rules_query_strings(tmp_path):
    links = [(f"{SITE}/list/?page={i}", f"p{i}") for i in range(1, 6)] + [(f"{SITE}/list/", "list")]
    write_site(tmp_path, HOST, {"/list/": html("List")})

    def followed(**settings):
        result = _rules_crawl(tmp_path, SITE + "/", links, **settings)
        return sorted(e.url for e in result.entries if e.url != SITE + "/"), result.skipped["excluded"]

    keep, _ = followed()
    assert len(keep) == 6
    drop, _ = followed(**{"crawl.queryStrings": "drop"})
    assert drop == [SITE + "/list/"]
    some, excluded = followed(**{"crawl.queryStrings": "keepN", "crawl.queryStringsPerPath": 2})
    assert some == sorted([SITE + "/list/", SITE + "/list/?page=1", SITE + "/list/?page=2"]) and excluded == 3


