def test_sitemap_limits(tmp_path):
    """R-112: 10 MB at most, no entity declarations, two levels, 20 children of an index."""
    page = f"{SITE}/notes/n1/"
    write_site(tmp_path, HOST, {
        "/ok.xml": urlset([page]),
        "/big.xml": urlset([page]) + "<!--" + "x" * (10 * 1024 * 1024) + "-->",
        "/entity.xml": '<?xml version="1.0"?><!DOCTYPE x [<!ENTITY a "b">]>' + urlset([page]),
        "/level3.xml": sitemap_index([f"{SITE}/level2.xml"]),
        "/level2.xml": sitemap_index([f"{SITE}/ok.xml"]),
        "/two-levels.xml": sitemap_index([f"{SITE}/ok.xml"]),
        "/wide.xml": sitemap_index([f"{SITE}/child-{i}.xml" for i in range(21)]),
        **{f"/child-{i}.xml": urlset([f"{SITE}/notes/c{i}/"]) for i in range(21)},
    })
    fetcher = FixtureFetcher(tmp_path)

    def urls(name):
        with net.use_fetcher(fetcher):
            return run(builders.sitemap_urls(f"{SITE}/{name}", s()))

    assert urls("ok.xml") == [page] and urls("two-levels.xml") == [page]
    assert urls("big.xml") == [] and urls("entity.xml") == [] and urls("level3.xml") == []
    wide = urls("wide.xml")
    assert len(wide) == 20 and f"{SITE}/notes/c20/" not in wide
    # Auto with only an oversized sitemap has no usable one: it falls back to the model.
    write_site(tmp_path, HOST, {"/": html("Home"), "/robots.txt": f"Sitemap: {SITE}/big.xml\n"})
    model = ScriptedChatModel()
    result = go(SITE + "/", s(**{"crawl.strategy": "auto"}), fetcher=FixtureFetcher(tmp_path), llm=model)
    assert result.stats["strategy"] == "llm" and result.entries[0].url == SITE + "/"


