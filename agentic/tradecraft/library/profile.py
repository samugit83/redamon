"""The session profile library hints search by (Q6, T8.1).

Built only from structured run data and fixed lists (Q12): the skill's topic (a built-in skill is
a vocabulary topic), the phase, the target's technologies as vocabulary ids, CVE ids as the CVE
pattern finds them in recon data and in the target's tool results, the vocabulary's keywords found
in the user's message, and whether a target's tool result shows a block (fixed patterns). A tool
result can add only a pattern-checked CVE id or the fixed fact that a block was seen: its text
never becomes a query, since it comes from the target and could be planted.

``target_info`` is filled from the model's analysis of tool output, so it is target-influenced too:
a technology is kept only when the vocabulary knows it, a CVE id only when the pattern matches.

The profile of the last check is kept in the run's hint log (an entry of kind ``profile``), so a
resume that runs the think node again on the saved state meets no checkpoint twice.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Iterable, Mapping, Optional

from tradecraft.ingest import entities as entity_rules
from tradecraft.vocab import load_vocab

MAX_TECHS = 30
MAX_CVES = 50
MAX_KEYWORDS = 3
MAX_RESULTS = 50
RESULT_CHARS = 20_000

# Tools whose output is the library or the web, never the target's.
NOT_TARGET = frozenset({"tradecraft_lookup", "tradecraft_search", "tradecraft_ask", "web_search", "google_dork"})
# The graph tools answer with the recon data's own status codes ("403" on a stored endpoint), not
# with a response the agent just got: no block is read from them.
NO_BLOCK_FROM = NOT_TARGET | {"query_graph", "graph_schema", "graph_summary"}

_HTTP_403 = re.compile(r"\bHTTP/\d(?:\.\d)?\s+403\b|\b403\s+Forbidden\b", re.IGNORECASE)
_BLOCKED = re.compile(r"\bblocked\b", re.IGNORECASE)
# The block pages of common web application firewalls, in their own words. The vocabulary has no
# such list; a vendor's name alone is not here, because its sites send it in every response.
WAF_SIGNATURES = (
    "attention required! | cloudflare",
    "sorry, you have been blocked",
    "the requested url was rejected",
    "this error was generated by mod_security",
    "sucuri website firewall",
    "incapsula incident id",
    "request unsuccessful. incapsula",
    "your access to this site has been limited",
    "you don't have permission to access",
    "aws waf",
)


@dataclass(frozen=True)
class Profile:
    topic: Optional[str]
    phase: str
    technologies: tuple[str, ...] = ()
    cves: tuple[str, ...] = ()
    keywords: tuple[str, ...] = ()
    blocked: bool = False
    # The tool results already read for CVE ids and blocks: a resume reads them once.
    results: tuple[str, ...] = ()

    def to_log(self) -> dict[str, Any]:
        return {"kind": "profile", "topic": self.topic, "phase": self.phase,
                "technologies": list(self.technologies), "cves": list(self.cves), "keywords": list(self.keywords),
                "blocked": self.blocked, "results": list(self.results)}

    @classmethod
    def from_log(cls, entry: Optional[Mapping[str, Any]]) -> Optional["Profile"]:
        """The profile a run saved, or None. The saved state is read like any input: only the
        expected types, within the caps."""
        if not isinstance(entry, Mapping):
            return None
        topic = entry.get("topic")
        phase = entry.get("phase")
        return cls(topic=topic if isinstance(topic, str) and topic in load_vocab().topic_ids else None,
                   phase=phase if isinstance(phase, str) else "",
                   technologies=_strings(entry.get("technologies"), MAX_TECHS),
                   cves=tuple(c for c in _strings(entry.get("cves"), MAX_CVES) if entity_rules.cve_ids(c) == [c]),
                   keywords=_strings(entry.get("keywords"), MAX_KEYWORDS),
                   blocked=entry.get("blocked") is True,
                   results=_strings(entry.get("results"), MAX_RESULTS))


def _strings(value: Any, cap: int) -> tuple[str, ...]:
    out: list[str] = []
    for item in value if isinstance(value, (list, tuple)) else ():
        if isinstance(item, str) and item and item not in out:
            out.append(item[:200])
    return tuple(out[:cap])


def _get(obj: Any, key: str) -> Any:
    return obj.get(key) if isinstance(obj, Mapping) else getattr(obj, key, None)


def _union(first: Iterable[str], then: Iterable[str], cap: int) -> tuple[str, ...]:
    out: list[str] = []
    for item in [*first, *then]:
        if item not in out:
            out.append(item)
    return tuple(out[:cap])


def topic_of(state: Mapping[str, Any]) -> Optional[str]:
    path = str(state.get("attack_path_type") or "")
    return path if path in load_vocab().topic_ids else None


def objective_of(state: Mapping[str, Any]) -> str:
    objectives = state.get("conversation_objectives") or []
    index = state.get("current_objective_index")
    if isinstance(index, int) and 0 <= index < len(objectives) and isinstance(objectives[index], Mapping):
        return str(objectives[index].get("content") or "")
    return str(state.get("original_objective") or "")


def keywords_in(text: str) -> tuple[str, ...]:
    """The vocabulary's keywords the text names, the longest first, none inside a longer one
    already kept: the vocabulary's words, never the text's own."""
    vocab = load_vocab()
    lowered = " ".join(str(text or "").lower().split())
    phrases = {p for words in [*vocab.keywords.values(), *vocab.kind_keywords.values()] for p in words}
    found: list[str] = []
    for phrase in sorted(phrases, key=lambda p: (-len(p), p)):
        if any(phrase in kept for kept in found):
            continue
        if re.search(rf"(?<![a-z0-9]){re.escape(phrase)}(?![a-z0-9])", lowered):
            found.append(phrase)
        if len(found) >= MAX_KEYWORDS:
            break
    return tuple(found)


def new_results(state: Mapping[str, Any]) -> list[tuple[str, str, str]]:
    """(id, tool, output) of the tool results the think node is about to read: the single step's
    and the plan wave's, before their analysis."""
    out: list[tuple[str, str, str]] = []
    step = state.get("_current_step")
    if isinstance(step, Mapping) and step.get("tool_output") is not None and not step.get("output_analysis"):
        ident = str(step.get("step_id") or f"step:{state.get('current_iteration', 0)}")
        out.append((ident, str(step.get("tool_name") or ""), str(step.get("tool_output") or "")))
    plan = state.get("_current_plan")
    if isinstance(plan, Mapping) and not plan.get("_analyzed"):
        wave = str(plan.get("wave_id") or f"plan:{state.get('current_iteration', 0)}")
        for n, item in enumerate(plan.get("steps") or []):
            if isinstance(item, Mapping) and item.get("tool_output") is not None:
                out.append((f"{wave}:{n}", str(item.get("tool_name") or ""), str(item.get("tool_output") or "")))
    return out[:MAX_RESULTS]


def shows_block(text: str) -> bool:
    head = text[:RESULT_CHARS]
    lowered = head.lower()
    return bool(_HTTP_403.search(head) or _BLOCKED.search(head) or any(s in lowered for s in WAF_SIGNATURES))


def build(state: Mapping[str, Any], previous: Optional[Profile]) -> Profile:
    """The profile now: what the run knows, with what the previous check had already seen."""
    from tradecraft.library.search import technologies_of

    target = state.get("target_info") or {}
    techs = technologies_of(_get(target, "technologies") or [])
    cves: list[str] = []
    for value in _get(target, "vulnerabilities") or []:
        if isinstance(value, str):
            cves += entity_rules.cve_ids(value)
    checked = set(previous.results) if previous else set()
    results = new_results(state)
    blocked = False
    for ident, tool, output in results:
        if ident in checked:
            continue
        if tool not in NOT_TARGET:
            cves += entity_rules.cve_ids(output[:RESULT_CHARS])
        if tool not in NO_BLOCK_FROM and shows_block(output):
            blocked = True
    return Profile(
        topic=topic_of(state),
        phase=str(state.get("current_phase") or "informational"),
        technologies=_union(previous.technologies if previous else (), techs, MAX_TECHS),
        cves=_union(previous.cves if previous else (), cves, MAX_CVES),
        keywords=keywords_in(objective_of(state)),
        blocked=blocked or bool(previous and previous.blocked),
        results=tuple(ident for ident, _t, _o in results) or (previous.results if previous else ()),
    )


def checkpoints(previous: Optional[Profile], current: Profile) -> tuple[str, ...]:
    """The checkpoints ``current`` reaches since ``previous``: at a run's start only the skill
    chosen; then the skill changed, the phase changed, a technology or CVE the profile did not
    have, a first block."""
    if previous is None:
        return ("skill",) if current.topic else ()
    fired = []
    if current.topic and current.topic != previous.topic:
        fired.append("skill")
    if current.phase != previous.phase:
        fired.append("phase")
    if set(current.technologies) - set(previous.technologies):
        fired.append("technology")
    if set(current.cves) - set(previous.cves):
        fired.append("cve")
    if current.blocked and not previous.blocked:
        fired.append("block")
    return tuple(fired)
