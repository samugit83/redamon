'use client'

import { memo, useMemo, useState } from 'react'
import { RedZoneTableShell } from './RedZoneTableShell'
import { useRedZoneTable } from './useRedZoneTable'
import { normalizeSeverity } from './types'
import type { RedZoneExportConfig } from './exportCsv'
import { useRedZoneFilters, type RedZoneFilterColumn } from './useRedZoneFilters'
import {
  UPDATED_AT_COLUMN,
  UpdatedAtCell,
  UpdatedAtTh,
  useUpdatedAtSort,
} from './updatedAt'
import { NODE_ID_COLUMN, NodeIdCell, NodeIdTh } from './nodeId'
import { MuteNodeButton } from '../MuteNode'
import { SeverityBadge, Mono, Truncated, NumCell, filterRowsByText } from './formatters'
import { maskSnippet } from './redact'
import { SecretValue } from '@/components/ui'
import rowStyles from './RedZoneTableRow.module.css'

export interface RouteExposureRow {
  nodeId: string | null
  host: string
  path: string
  url: string | null
  kind: string | null
  routeClass: string | null
  severity: string | null
  confidence: number | null
  /** pending: a lead awaiting the agent; confirmed: the agent proved it; finding: a signature proved it. */
  status: 'pending' | 'confirmed' | 'finding'
  anonStatus: number | null
  authedStatus: number | null
  authExpectedBy: string
  leakSignals: string
  piiTypes: string
  signature: string | null
  generatedBy: string | null
  evidenceSnippet: string | null
  /** The secrets the anonymous answer held and, index by index, their detector. */
  secretValues?: string[]
  secretValueTypes?: string[]
  /** Graph `updated_at` of the node this row is built from. */
  updatedAt: unknown
}

const PAGE_SIZE = 100

/** Module-level: the filter profiles are keyed off these. */
const COLUMNS: RedZoneFilterColumn[] = [
  NODE_ID_COLUMN,
  { key: 'host', header: 'Host' },
  { key: 'path', header: 'Path' },
  { key: 'kind', header: 'Kind' },
  { key: 'routeClass', header: 'Route class' },
  { key: 'severity', header: 'Severity' },
  { key: 'status', header: 'Status' },
  { key: 'anonStatus', header: 'Anonymous status' },
  { key: 'authedStatus', header: 'Logged-in status' },
  { key: 'authExpectedBy', header: 'Auth expected by' },
  { key: 'leakSignals', header: 'Leak signals' },
  { key: 'piiTypes', header: 'Personal data kinds' },
  { key: 'generatedBy', header: 'Generated by' },
  { key: 'signature', header: 'Signature' },
  { key: 'confidence', header: 'Confidence' },
  { key: 'evidenceSnippet', header: 'Evidence' },
  UPDATED_AT_COLUMN,
]

/** The export carries the secrets whole, one per line: the operator's own file.
 *  They are no filter column: a filter would list every value. */
const EXPORT_COLUMNS: RedZoneFilterColumn[] = [
  ...COLUMNS.slice(0, -1),
  { key: 'secretValues', header: 'Secrets' },
  COLUMNS[COLUMNS.length - 1],
]

function SecretsCell({ values, types }: { values?: string[]; types?: string[] }) {
  if (!values?.length) return <span className={rowStyles.nullCell}>-</span>
  return (
    <span className={rowStyles.secretStack}>
      {values.map((v, i) => <SecretValue key={`${i}-${v.length}`} label={types?.[i]} value={v} />)}
    </span>
  )
}

const STATUS_LABEL: Record<RouteExposureRow['status'], string> = {
  pending: 'Pending',
  confirmed: 'Confirmed',
  finding: 'Finding',
}

interface Props { projectId: string | null }

export const RouteExposureTable = memo(function RouteExposureTable({ projectId }: Props) {
  const { data, isLoading, error, refetch } = useRedZoneTable<RouteExposureRow>('routeExposure', projectId)
  const [search, setSearch] = useState('')
  const [limit, setLimit] = useState(PAGE_SIZE)

  // The snippet is target text: masked again and only ever rendered as text.
  const rows = useMemo(
    () => (data?.rows ?? []).map(r => ({ ...r, evidenceSnippet: maskSnippet(r.evidenceSnippet) })),
    [data],
  )
  const searched = useMemo(() => filterRowsByText(rows, search), [rows, search])
  const { filteredRows: filtered, filterUi } = useRedZoneFilters({
    rows: searched, columns: COLUMNS, projectId, slug: 'routeExposure',
  })
  const { sortedRows, sortDir, toggleSort } = useUpdatedAtSort(filtered)
  const sliced = useMemo(() => sortedRows.slice(0, limit), [sortedRows, limit])

  const exportConfig = useMemo<RedZoneExportConfig | undefined>(() =>
    rows.length > 0
      ? {
          rows: sortedRows.map(r => ({ ...r, secretValues: (r.secretValues ?? []).join('\n') })),
          sheetName: 'RouteExposure', fileSlug: 'redzone-route-exposure', columns: EXPORT_COLUMNS,
        }
      : undefined,
    [sortedRows, rows.length],
  )

  const pending = rows.filter(r => r.status === 'pending').length
  const findings = rows.filter(r => r.status === 'finding').length
  const meta = rows.length
    ? `${findings} finding(s) · ${pending} pending lead(s) · ${rows.length} total`
    : undefined

  return (
    <RedZoneTableShell
      title="Route Exposure"
      meta={meta}
      search={search}
      onSearchChange={setSearch}
      searchPlaceholder="Search host, path, kind..."
      exportConfig={exportConfig}
      filterUi={filterUi}
      onRefresh={refetch}
      isLoading={isLoading}
      error={error}
      rowCount={rows.length}
      filteredRowCount={filtered.length}
      emptyLabel="No route exposure results yet. Enable Route Exposure in Vulnerability Scanning and run a recon."
    >
      <table className={rowStyles.table}>
        <thead>
          <tr>
            <NodeIdTh />
            <th>Host</th>
            <th>Path</th>
            <th>Kind</th>
            <th>Route class</th>
            <th>Sev</th>
            <th>Status</th>
            <th>Anon</th>
            <th>Logged in</th>
            <th>Auth expected by</th>
            <th>Leak signals</th>
            <th>Generated by</th>
            <th>Secrets</th>
            <th>Evidence</th>
            <UpdatedAtTh dir={sortDir} onToggle={toggleSort} />
            <th />
          </tr>
        </thead>
        <tbody>
          {sliced.map((r, i) => (
            <tr key={`${r.nodeId ?? r.path}-${r.kind}-${i}`}>
              <td><NodeIdCell value={r.nodeId} /></td>
              <td><Mono>{r.host || '-'}</Mono></td>
              <td><Truncated text={r.path} max={80} /></td>
              <td><Mono>{r.kind || '-'}</Mono></td>
              <td><Mono>{r.routeClass || '-'}</Mono></td>
              <td><SeverityBadge severity={normalizeSeverity(r.severity)} /></td>
              <td><Mono>{STATUS_LABEL[r.status] ?? r.status}</Mono></td>
              <td><NumCell value={r.anonStatus} /></td>
              <td><NumCell value={r.authedStatus} /></td>
              <td><Truncated text={r.authExpectedBy || '-'} max={240} /></td>
              <td><Truncated text={r.leakSignals || '-'} max={80} /></td>
              <td><Mono>{r.generatedBy || '-'}</Mono></td>
              <td><SecretsCell values={r.secretValues} types={r.secretValueTypes} /></td>
              <td><Truncated text={r.evidenceSnippet} max={120} /></td>
              <td><UpdatedAtCell value={r.updatedAt} /></td>
              <td><MuteNodeButton name={r.url || r.path || 'route exposure finding'} graphId={r.nodeId} label="Vulnerability" /></td>
            </tr>
          ))}
        </tbody>
      </table>
      {limit < filtered.length && (
        <div className={rowStyles.loadMoreBar}>
          <button className={rowStyles.loadMoreBtn} onClick={() => setLimit(l => l + PAGE_SIZE)}>
            Showing {sliced.length} of {filtered.length} - Load more
          </button>
        </div>
      )}
    </RedZoneTableShell>
  )
})
