/**
 * Every API route (`src/app/api/**\/route.ts`) and the guard it runs (DV-03, T20).
 *
 * Data for tests until Phase 3, which adds each route's permission: nothing reads it
 * at run time. `routeManifest.test.ts` walks the tree and fails, naming the file, on a
 * route that is not listed, an entry without a file, stale methods, or a class its
 * calls no longer give.
 *
 * Kept by hand, maintained with `node scripts/gen-route-manifest.mjs` (from webapp/),
 * which adds new route files, drops gone ones, refreshes methods, re-derives the class
 * of an entry without a `note`, and rewrites `routeManifest.json`, the copy `.mjs`
 * scripts read. A class the calls do not give (an inline role check, a guard the
 * classifier cannot see) carries a `note` saying why, and the generator never changes
 * it. Comments inside the list are not kept: put the reason in `note`.
 */

export const GUARD_CLASSES = [
  /** Sessionless at the middleware (`PUBLIC_PATHS`); the handler may check its own credential. */
  'public',
  /** Plugin call token or runner key (`TOKEN_AUTH_PREFIXES`); never a session. */
  'plugin-token',
  /** The internal service key only (`isInternalRequest`). */
  'internal',
  /** Accepts the scanner key (`isScannerRequest`), with or without the internal key. */
  'scanner',
  /** The caller must own the project (`guardProject`, `requireProjectAccess`, `requireProjectOwner`, ...). */
  'project',
  /** The caller must own the conversation (`requireConversationAccess`, `...BySession`). */
  'conversation',
  /** The caller must be the user the path names, or an admin (`requireUserAccess`, `requireOwnBrowserRequest`). */
  'user',
  /** Admin by the session's role, which getSession reads from the database (`requireAdmin`, inline `session.role` checks). */
  'admin-jwt',
  /** Admin by the role read from the database (`requirePluginAdmin`, `lifecyclePost`, `lifecycleGet`). */
  'admin-db',
  /** Scoped to the effective user's own rows (`requireEffectiveUser`, `ownerScope`), no project check. */
  'effective-user',
  /** Reads the login session (`getSession`, `requireSession`), no ownership check. */
  'session',
  /** Only the middleware's JWT check: the handler reads no session at all. */
  'login-only',
  /** A guard none of the above describes (`strictContext`, `handleAction`). */
  'other',
] as const

export type GuardClass = (typeof GUARD_CLASSES)[number]

export type HttpMethod = 'GET' | 'HEAD' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'OPTIONS'

export interface RouteManifestEntry {
  /** URL path with the folder names of dynamic segments: `/api/projects/[id]`. */
  path: string
  guard: GuardClass
  /** The handlers the route file exports, in the order GET HEAD POST PUT PATCH DELETE OPTIONS. */
  methods: HttpMethod[]
  /** From Phase 3: one permission for every method, or one per method. */
  permission?: string | Partial<Record<HttpMethod, string>>
  /** Why the class is what it is, when the calls alone do not say. */
  note?: string
}

