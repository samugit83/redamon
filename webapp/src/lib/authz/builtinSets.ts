export const BUILTIN_SETS: readonly BuiltinSet[] = Object.freeze([...BUILTIN_MEMBER_SETS, ...BUILTIN_ADMIN_PROFILES])

export const BUILTIN_SET_IDS: readonly BuiltinSetId[] = Object.freeze(BUILTIN_SETS.map((s) => s.id))

/** Never assigned a set and no instance default: this one (§14.3). */
export const DEFAULT_MEMBER_SET_ID: BuiltinSetId = 'builtin:default-member'
/** Assigned sets that are all gone resolve here, never to the default (fail closed, §4.6). */
export const NO_ACCESS_SET_ID: BuiltinSetId = 'builtin:no-access'
/** An admin with no profile recorded: today's admins (§4.5). */
export const FULL_ADMIN_PROFILE_ID: BuiltinSetId = 'builtin:full-admin'

const BY_ID: ReadonlyMap<string, BuiltinSet> = new Map(BUILTIN_SETS.map((s) => [s.id, s]))

export function isBuiltinSetId(value: unknown): value is BuiltinSetId {
  return typeof value === 'string' && BY_ID.has(value)
}

export function builtinSet(id: string): BuiltinSet | undefined {
  return BY_ID.get(id)
}
